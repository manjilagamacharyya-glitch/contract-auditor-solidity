import { keccak256, toUtf8Bytes } from 'ethers';
import { Finding, AuditResult } from './types.js';

export function computeContractHash(source: string): string {
  return keccak256(toUtf8Bytes(source));
}

export function computeReportHash(reportMarkdown: string): string {
  return keccak256(toUtf8Bytes(reportMarkdown));
}

export function generateReportMarkdown(params: {
  score: number;
  summary: string;
  findings: Finding[];
  contractHash: string;
  engine: 'hybrid' | 'rule-only';
  dateStr?: string;
}): string {
  const { score, summary, findings, contractHash, engine, dateStr } = params;
  const auditDate = dateStr || new Date().toISOString().split('T')[0];

  const criticalCount = findings.filter((f) => f.severity === 'Critical').length;
  const highCount = findings.filter((f) => f.severity === 'High').length;
  const mediumCount = findings.filter((f) => f.severity === 'Medium').length;
  const lowCount = findings.filter((f) => f.severity === 'Low').length;
  const infoCount = findings.filter((f) => f.severity === 'Info').length;

  let originLabel = (origin: Finding['origin']) => {
    if (origin === 'both') return 'Rule & AI';
    if (origin === 'ai') return 'AI Review';
    return 'Rule Check';
  };

  let tableRows = findings.length === 0
    ? '| None | No vulnerabilities detected | - | - |\n'
    : findings
        .map(
          (f) =>
            `| ${f.severity} | ${f.name} | Line ${f.line} | ${originLabel(f.origin)} |`
        )
        .join('\n');

  let detailsSection = findings.length === 0
    ? 'No security vulnerabilities or code quality issues were identified.'
    : findings
        .map((f, i) => {
          return `### ${i + 1}. [${f.severity}] ${f.name}

- **Line:** ${f.line}
- **Detection Source:** ${originLabel(f.origin)}
- **Description:** ${f.description}
- **Suggested Remediation:**
\`\`\`solidity
${f.fix}
\`\`\`
`;
        })
        .join('\n\n');

  return `# Smart Contract Security Audit Report

- **Date:** ${auditDate}
- **Contract Hash (keccak256):** \`${contractHash}\`
- **Audit Engine:** ${engine === 'hybrid' ? 'Hybrid (Automated Detectors + Gemini AI)' : 'Automated Rule Detectors'}
- **Security Score:** **${score} / 100**

---

## Executive Summary

${summary}

### Severity Breakdown
- **Critical:** ${criticalCount}
- **High:** ${highCount}
- **Medium:** ${mediumCount}
- **Low:** ${lowCount}
- **Informational:** ${infoCount}

---

## Findings Overview

| Severity | Issue | Location | Source |
| :--- | :--- | :--- | :--- |
${tableRows}

---

## Detailed Findings

${detailsSection}

---

*Report generated by Contract Auditor. Anchored on Sepolia testnet.*
`;
}
